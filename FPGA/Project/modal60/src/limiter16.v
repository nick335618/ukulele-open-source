// ============================================================================
// limiter16.v —— 最终柔和限幅（防多音叠加硬削顶，v7；v11 支持加宽输入）
// ----------------------------------------------------------------------------
// 背景：25 音音库中低音区 7 个长尾音同在一个引擎，快速连弹时多音叠加可使
//       总线远超 16bit 满幅；旧设计在"引擎级 + 顶层级"各硬饱和一次，产生
//       +32767 平台（电吉他失真质感，bench4_音频失真原因报告 §2）。
// 本模块：单点柔和限幅替代硬削顶——
//   - 线性区 |x| <= THR(28000)：输出 = 输入（完全直通，单音/少量叠加不变，
//     与模型 bank wav 逐位一致的性质得以保留）；
//   - |x| > THR：斜率压缩 1/4（柔和），并封顶 32000 < 32767，无满幅平台。
// v11：输入位宽参数化（W 默认 20；top_bench4 在引擎和之后加了瞬态与琴箱
//       共鸣，中间和加宽到 22bit 再进本限幅，THR/封顶语义不变，仍输出 16bit）。
// 纯组合（每采样节拍由顶层寄存器取样），逻辑浅，不占时序。
// ============================================================================
module limiter16 #(
    parameter W   = 20,        // 输入位宽（有符号）
    parameter THR = 28000      // 线性阈值（高于典型单音峰值 ~5k、低音 3~4 音叠加 ~19k）
) (
    input  wire signed [W-1:0] x,
    output wire signed [15:0] y
);
    localparam signed [W-1:0] THR_W = THR;
    localparam signed [W-1:0] MAX_W = 32'sd32000;
    wire signed [W-1:0] ax   = (x < 0) ? -x : x;      // |x|
    wire signed [W-1:0] over = ax - THR_W;            // >0 进入压缩区
    // 压缩：comp = THR + (|x|-THR)/4（THR 与封顶 32000 均为绝对电平，不随 W 缩放）
    wire signed [W-1:0] comp = (over <= 0) ? ax : (THR_W + (over >>> 2));
    wire signed [W-1:0] mag  = (comp > MAX_W) ? MAX_W : comp;   // 封顶（值<2^16，截断无损）
    assign y = (x < 0) ? -$signed(mag[15:0]) : $signed(mag[15:0]);
endmodule
